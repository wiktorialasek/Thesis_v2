def trade_decision(pred_label_str):
    if pred_label_str == "up":
        return "buy"
    elif pred_label_str == "down":
        return "sell"
    else:
        return "hold"

test_pred_df['trade_decision'] = test_pred_df['pred_label_str'].apply(trade_decision)

def pnl_from_decision(row):
    decision = row['trade_decision']
    if RET_COL not in row or pd.isna(row[RET_COL]):
        return 0.0
    ret = row[RET_COL]  # np. zmiana % vs open

    if decision == "buy":
        return ret
    elif decision == "sell":
        return -ret
    else:
        return 0.0

test_pred_df['pnl_model'] = test_pred_df.apply(pnl_from_decision, axis=1)

