import torch.nn as nn
from transformers import AutoModel, PreTrainedModel
from transformers.modeling_outputs import SequenceClassifierOutput

class FinBertWithFeatures(PreTrainedModel):
    config_class = AutoModel.from_pretrained(MODEL_NAME, attn_implementation="eager").config.__class__

    def __init__(self, config, num_extra_features, num_labels):
        super().__init__(config)
        self.num_labels = num_labels
        self.bert = AutoModel.from_pretrained(MODEL_NAME, config=config, attn_implementation="eager")
        self.dropout = nn.Dropout(0.1)
        self.classifier = nn.Linear(config.hidden_size + num_extra_features, num_labels)

        self.init_weights()

    def forward(
        self,
        input_ids=None,
        attention_mask=None,
        labels=None,
        llm_sent_tweet_num=None,
        llm_sent_quote_num=None,
        llm_stance_num=None,
        llm_impact_num=None,
        llm_sarcasm_num=None,
        llm_conf_num=None,
        tesla_keywords_num=None,
        **kwargs
    ):
        outputs = self.bert(
            input_ids=input_ids,
            attention_mask=attention_mask,
        )
        # cls embedding
        if hasattr(outputs, "pooler_output") and outputs.pooler_output is not None:
            pooled = outputs.pooler_output
        else:
            pooled = outputs.last_hidden_state[:, 0]

        # zlepienie cech numerycznych
        extra_feats_list = [
            llm_sent_tweet_num,
            llm_sent_quote_num,
            llm_stance_num,
            llm_impact_num,
            llm_sarcasm_num,
            llm_conf_num,
            tesla_keywords_num,
        ]
        extra_feats = torch.stack(extra_feats_list, dim=1).float()

        x = torch.cat([pooled, extra_feats], dim=1)
        x = self.dropout(x)
        logits = self.classifier(x)

        loss = None
        if labels is not None:
            loss_fct = nn.CrossEntropyLoss()
            loss = loss_fct(logits.view(-1, self.num_labels), labels.view(-1))

        return SequenceClassifierOutput(
            loss=loss,
            logits=logits,
        )

