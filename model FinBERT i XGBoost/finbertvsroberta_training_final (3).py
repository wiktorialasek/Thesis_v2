# 1. Tekst, na którym będziemy liczyć sentyment
#    - jeśli to retweet i jest combined_quote_info -> użyj głównie cytowanego tweeta
#    - w pozostałych przypadkach: clean_text + (ewentualnie) combined_quote_info jako kontekst
def build_sent_text(row):
    base = ""
    if pd.notna(row.get("clean_text")):
        base = str(row["clean_text"]).strip()

    quote = ""
    if "combined_quote_info" in row and pd.notna(row["combined_quote_info"]):
        quote = str(row["combined_quote_info"]).strip()

    # jeśli to retweet i mamy cytowaną treść, traktuj cytat jako główny tekst
    if row.get("isRetweet", 0) == 1 and quote:
        text = quote
    else:
        text = base
        if quote:
            text = (text + " " + quote).strip()

    return text

