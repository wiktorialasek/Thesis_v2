    s_sorted = s.sort_values(ascending=False)

    fig, ax = plt.subplots(figsize=(7, 4))
    ax.bar(s_sorted.index, s_sorted.values)
    ax.set_ylabel("Udział [%]")
    ax.set_title("Rozkład typów zgodności modeli")
    ax.set_xticklabels(s_sorted.index, rotation=45, ha="right")
    ax.set_ylim(0, 100)

    # dodanie wartości nad słupkami (opcjonalne, ale ładne do pracy)
    for i, v in enumerate(s_sorted.values):
        ax.text(i, v + 1, f"{v:.1f}%", ha="center", va="bottom", fontsize=8)

    fig.tight_layout()
    plt.show()


