def run_pipe(pipe, texts, batch_size=32):
    labels, scores = [], []
    for i in range(0, len(texts), batch_size):
        batch = texts[i:i + batch_size]
        outputs = pipe(batch)
        for out in outputs:
            # normalizujemy label do małych liter, żeby łatwo porównać z llm_sent_tweet
            labels.append(out["label"].lower())
            scores.append(float(out["score"]))
    return labels, scores

