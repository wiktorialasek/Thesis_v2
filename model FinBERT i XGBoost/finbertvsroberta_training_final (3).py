def plot_agreement_distribution(agreement_series, as_percent=True):
    """
    agreement_series : pandas.Series
        Index: etykiety typu zgodności (np.
            ['wszyscy trzej', 'tylko LLM–FinBERT', ...])
        Values: liczności lub % (jeśli as_percent=False, policzymy % sami).
    as_percent : bool
        Jeśli True i suma != 100, wartości zostaną przeskalowane do %.
    """
    s = agreement_series.copy()

