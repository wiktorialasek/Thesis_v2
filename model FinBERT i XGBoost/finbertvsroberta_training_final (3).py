def run_model(ckpt: str, texts, prefix: str, batch_size: int = 64) -> pd.DataFrame:
    tok = AutoTokenizer.from_pretrained(ckpt, use_fast=True)
    mod = AutoModelForSequenceClassification.from_pretrained(ckpt)
    pipe = TextClassificationPipeline(
        model=mod, tokenizer=tok, device=device, truncation=True, max_length=128
    )
    # pełny rozkład dla każdej próbki
    out = pipe(texts, batch_size=batch_size, return_all_scores=True)

    def norm_label(name: str) -> str:
        n = name.lower().replace("label_", "")
        if n.startswith("neg"): return "negative"
        if n.startswith("neu"): return "neutral"
        if n.startswith("pos"): return "positive"
        # dla modeli z LABEL_0/1/2 spróbuj mapować po id2label
        if n in {"0","1","2"}:  # awaryjnie: typowa kolejność CardiffNLP: neg, neu, pos
            return {"0":"negative","1":"neutral","2":"positive"}[n]
        return n

    rows, labels, maxprobs = [], [], []
    for row in out:
        d = {norm_label(s["label"]): float(s["score"]) for s in row}
        pneg = d.get("negative", 0.0); pneu = d.get("neutral", 0.0); ppos = d.get("positive", 0.0)
        rows.append([pneg, pneu, ppos])
        arr = np.array([pneg, pneu, ppos]); labels.append(["negative","neutral","positive"][arr.argmax()])
        maxprobs.append(float(arr.max()))
    res = pd.DataFrame(rows, columns=[f"{prefix}_p_negative", f"{prefix}_p_neutral", f"{prefix}_p_positive"])
    res[f"{prefix}_label"] = labels
    res[f"{prefix}_maxprob"] = maxprobs
    return res



