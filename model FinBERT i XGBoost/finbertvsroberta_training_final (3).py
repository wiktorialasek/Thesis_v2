def classify_agreement(row):
    l = row['llm_sent_tweet']
    f = row['fin_sent_tweet']
    r = row['rob_sent_tweet']

    all_equal = (l == f == r)
    lf = (l == f) and not all_equal
    lr = (l == r) and not all_equal
    fr = (f == r) and not all_equal

    if all_equal:
        return "wszyscy trzej"
    elif lf and not (lr or fr):
        return "tylko LLM–FinBERT"
    elif lr and not (lf or fr):
        return "tylko LLM–RoBERTa"
    elif fr and not (lf or lr):
        return "tylko FinBERT–RoBERTa"
    # If none of the pairwise agreements are exclusive or all agree, check if no agreement at all.
    # This covers cases where two agree, but not exclusively, or none agree.
    # The previous logic in GPMLRjSsvyAl for `none_agree` already handles this correctly,
    # but we need to ensure this function reflects it for cases not covered by the `if/elif` above
    # For this specific function, we prioritize specific types of agreement.
    # If no specific type of agreement matches the defined conditions,
    # it falls into 'brak zgodności'.
    else:
        return "brak zgodności"

