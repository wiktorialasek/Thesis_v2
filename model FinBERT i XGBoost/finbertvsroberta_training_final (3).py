def confusion_row_normalized(df_cm, col_true, col_pred):
    """
    Zwraca macierz pomyłek (DataFrame) znormalizowaną w wierszach (0–1).
    wiersz = etykieta modelu "true", kolumna = etykieta modelu "pred".
    """
    cm = (
        df_cm
        .groupby([col_true, col_pred])
        .size()
        .unstack(fill_value=0)
        .astype(float)
    )
    cm = cm.div(cm.sum(axis=1), axis=0)  # normalizacja wierszami
    return cm

